local function resolveVmsPropertyEntrance(property)
    if type(property) ~= "table" then
        return nil
    end

    if property.object_id then
        local buildingOk, building = pcall(function()
            return exports["vms_housing"]:GetProperty(property.object_id)
        end)
        if buildingOk and type(building) == "table" and building.type == "building" then
            property = building
        end
    end

    return Sky.Housing.ResolvePropertyEntrance(property)
end

Sky.Housing.RegisterAdapter("vms_housing", function(source)
    if GetResourceState("vms_housing") ~= "started" then
        return nil
    end

    if IsDuplicityVersion() then
        local ok, playerProperty = pcall(function()
            return exports["vms_housing"]:GetPlayerCurrentProperty(source)
        end)
        if not ok or not playerProperty then
            return nil
        end

        local property
        ok, property = pcall(function()
            return exports["vms_housing"]:GetProperty(playerProperty)
        end)
        if not ok then
            return nil
        end

        return resolveVmsPropertyEntrance(property)
    end

    local ok, propertyId, property = pcall(function()
        return exports["vms_housing"]:IsPlayerInsideProperty()
    end)
    if not ok or not propertyId then
        return nil
    end
    if type(property) ~= "table" then
        ok, property = pcall(function()
            return exports["vms_housing"]:GetProperty(propertyId)
        end)
        if not ok then
            return nil
        end
    end

    return resolveVmsPropertyEntrance(property)
end)
